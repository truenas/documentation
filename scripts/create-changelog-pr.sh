#!/bin/bash
#
# Automated PR creation script for changelog CSV updates
# Adapted from scripts/create-software-status-pr.sh
#
# Run from inside a checkout of a version branch, after scripts/update-changelogs.py
# has modified static/data/*-changelog.csv and written changelog-update-summary.md.
#
#   BASE_BRANCH=27 bash scripts/create-changelog-pr.sh
#
# Unlike the software-status helper, this exits non-zero when the push or the PR
# fails, so the nightly job can mark the build UNSTABLE.

set -euo pipefail

if [ -z "${BASE_BRANCH:-}" ]; then
    echo "❌ BASE_BRANCH is not set (the version branch to open the PR against, e.g. 27)"
    exit 1
fi

BRANCH_NAME="changelog-updates-${BASE_BRANCH}"
PR_TYPE="Bot"
PR_TITLE="Automated Changelog Update (${BASE_BRANCH})"
SUMMARY_FILE="changelog-update-summary.md"
DATA_GLOB="static/data/*-changelog.csv"

# Predefined Reviewers (GitHub usernames/teams)
PREDEFINED_REVIEWERS=("truenas/docs-team")

echo "========================================="
echo "Changelog PR Creation Script (${BASE_BRANCH})"
echo "========================================="

if [ ! -f "$SUMMARY_FILE" ]; then
    echo "❌ ${SUMMARY_FILE} not found in $(pwd) - run scripts/update-changelogs.py first"
    exit 1
fi

# Verify GitHub CLI is available and authenticated
if ! command -v gh &> /dev/null; then
    echo "❌ GitHub CLI (gh) not found. Please install: https://cli.github.com/"
    exit 1
fi

if ! gh auth status &> /dev/null; then
    echo "❌ GitHub CLI not authenticated. Run: gh auth login"
    exit 1
fi

echo "✅ GitHub CLI verified and authenticated"

# Configure git for commits (same bot identity as the software-status helper)
git config user.name "${GIT_AUTHOR_NAME:-TrueNAS Bot}"
git config user.email "${GIT_AUTHOR_EMAIL:-noreply@truenas.com}"

echo "✅ Git user configured: $(git config user.name) <$(git config user.email)>"

REVIEWERS_LIST=$(IFS=, ; echo "${PREDEFINED_REVIEWERS[*]}")

# The checkout below resets the working tree to origin/${BASE_BRANCH}, which would discard
# the refreshed CSVs (they are edits on this checkout, not on a branch). Save them first.
SAVE_DIR=$(mktemp -d)
trap 'rm -rf "$SAVE_DIR"' EXIT

shopt -s nullglob
CSV_FILES=($DATA_GLOB)
shopt -u nullglob

if [ ${#CSV_FILES[@]} -eq 0 ]; then
    echo "❌ No files match ${DATA_GLOB}"
    exit 1
fi

for f in "${CSV_FILES[@]}"; do
    cp "$f" "$SAVE_DIR/"
done
cp "$SUMMARY_FILE" "$SAVE_DIR/"

echo "Fetching latest changes from origin..."
git fetch origin

# Create or reset the PR branch to match the base branch (ensures no merge conflicts)
echo "Creating/resetting branch: ${BRANCH_NAME} from origin/${BASE_BRANCH}..."
git checkout -f -B "${BRANCH_NAME}" "origin/${BASE_BRANCH}"

# Put the refreshed files back on top of the fresh base
for f in "${CSV_FILES[@]}"; do
    cp "$SAVE_DIR/$(basename "$f")" "$f"
done

echo "Adding refreshed changelog CSVs..."
git add -- "${CSV_FILES[@]}"

if git diff --cached --quiet; then
    echo "✅ Nothing to commit against origin/${BASE_BRANCH} - the changes may already be merged."
    exit 0
fi

COMMIT_MSG="Update changelog CSVs for ${BASE_BRANCH}

Automated refresh from the public Jira changelog filters.

Generated by: scripts/update-changelogs.py
Timestamp: $(date -u '+%Y-%m-%d %H:%M:%S UTC')"

echo "Creating commit..."
git commit -m "$COMMIT_MSG"

# Force push so a still-open PR from an earlier night is updated rather than left stale
echo "Pushing branch to origin (force)..."
git push --force origin "$BRANCH_NAME"

PR_DESCRIPTION="Automated refresh of the ${BASE_BRANCH} changelog CSVs from the public Jira filters.

$(cat "$SAVE_DIR/$SUMMARY_FILE")

Descriptions are raw Jira text. Please review the changes before merging.

Generated by: \`scripts/update-changelogs.py\`
Timestamp: $(date -u '+%Y-%m-%d %H:%M:%S UTC')"

FINAL_PR_TITLE="$PR_TYPE: $PR_TITLE"

# Update the open PR if there is one; gh pr create fails when one already exists
EXISTING_PR=$(gh pr list --head "$BRANCH_NAME" --base "$BASE_BRANCH" --json number --jq '.[0].number')

if [ -n "$EXISTING_PR" ]; then
    echo "Found existing PR #$EXISTING_PR, updating..."
    gh pr edit "$EXISTING_PR" --title "$FINAL_PR_TITLE" --body "$PR_DESCRIPTION"
    echo "✅ Pull request #$EXISTING_PR updated"
else
    echo "Creating pull request..."
    gh pr create --base "$BASE_BRANCH" --head "$BRANCH_NAME" \
        --title "$FINAL_PR_TITLE" --body "$PR_DESCRIPTION" --reviewer "$REVIEWERS_LIST"
    echo "✅ Pull request created"
    echo "   Reviewers: $REVIEWERS_LIST"
fi

echo "========================================="
echo "PR creation complete!"
echo "========================================="
